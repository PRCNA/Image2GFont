const fs=require('node:fs');
const vm=require('node:vm');
const assert=require('node:assert/strict');
const html=fs.readFileSync('ocr_demo.html','utf8');
const fn=html.slice(html.indexOf('function validateCorrections'),html.indexOf("$('restore').onchange"));
const validate=vm.runInNewContext(fn+';validateCorrections');
const item={text:'original',box:[[0,0],[10,0],[10,10],[0,10]]};
const images=[{id:'image_01',sha256:'abc',lines:[item],characters:[item]}];
const edit={image:'image_01',kind:'line',index:0,original:item.text,text:'corrected',box:item.box};
const record={format:'Image2GFontOCRCorrections',schema_version:1,confirmed_for_font:false,source_manifest:[{id:'image_01',sha256:'abc'}],edits:{'image_01:line:0':edit}};
const copy=()=>JSON.parse(JSON.stringify(record));
assert.equal(validate(copy(),images,{})['image_01:line:0'].text,'corrected');
let bad=copy();bad.source_manifest[0].sha256='different';assert.throws(()=>validate(bad,images,{}));
bad=copy();bad.edits['image_01:line:0'].box[0][0]=42;assert.throws(()=>validate(bad,images,{}));
bad=copy();bad.edits['image_01:line:0'].index=5;assert.throws(()=>validate(bad,images,{}));
bad=copy();bad.edits['image_01:line:0'].original='changed';assert.throws(()=>validate(bad,images,{}));
const existing={'image_01:line:0':{...edit,text:'unsaved'}};
assert.throws(()=>validate(copy(),images,existing));assert.equal(existing['image_01:line:0'].text,'unsaved');
assert.equal(validate(copy(),images,record.edits)['image_01:line:0'].text,'corrected');
bad=copy();bad.edits['image_01:char:0']={...edit,kind:'character',text:'other'};assert.equal(Object.keys(validate(bad,images,{})).length,2);
bad=copy();bad.schema_version=2;assert.throws(()=>validate(bad,images,{}));
console.log('9 correction restore checks passed');
